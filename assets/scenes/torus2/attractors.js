// TORUS2 — the strange attractors the torus is morphed into (brief-torus2 spec 5; the user: "mix in different
// attractors like the thomas / 3 cells cnn attractor").
//
// The morph is an ADVECTION, not a lerp to a drawn attractor: at morph 1 every fibre point is carried along the
// attractor's flow field for STEPS fixed RK2 steps, so the closed ring deforms into a ribbon that follows the
// attractor's shape and stays a closed curve (the flow is a diffeomorphism). At 0 the fibre is the exact Hopf
// circle; in between the two are lerped. The integration is a pure function of the point — no wall clock, no
// Math.random(), the same for every frame — and it happens in R³ AFTER the stereographic projection, never on S³,
// so no advected point can cross the projection pole (DECISIONS §4: that is what blows a family off screen).
//
// Each field is normalised into the nest: a point p is mapped to u = (p − centre) / radius × EXT, advected, and
// mapped back, EXT being the attractor's own natural extent. The step size is not a magic number — it is solved so
// that STEPS steps travel TRAVEL of the attractor's extent, from the mean speed of the field measured on a fixed
// lattice at module load (deterministic: the same numbers on every machine).
//
// The four fields, with the constants the shader uses and their sources:
//   Thomas    (René Thomas 1999, "Deterministic chaos seen in terms of feedback circuits", Int. J. Bif. Chaos 9:1889)
//             ẋ = sin y − b x (cyclic), b = 0.208 — chaotic below b ≈ 0.208.
//   3-cell CNN (Arena, Baglio, Fortuna, Manganaro 1995, "Chua's circuit can be generated by CNN cells",
//             IEEE Trans. Circuits Syst. I 42(2):123–125 — the three-cell template) ẋᵢ = −xᵢ + Σⱼ aᵢⱼ f(xⱼ) with
//             f(x) = ½(|x+1| − |x−1|) and a = [[p₁, −s, −s], [−s, p₂, −r], [−s, r, p₃]], p = (1.24, 1.1, 1.0),
//             r = 4.4, s = 3.21. The brief's lean wrote the off-diagonal signs as [[·, −s, +s], [+s, ·, −r], …];
//             that template is NOT chaotic — every initial condition tried settles on a cycle of box 1.33–1.60 with
//             a largest Lyapunov exponent of −0.001…+0.007 (tools/test_torus2.js measures it). The template above
//             gives λ ≈ 0.118 from every initial condition tried, which is the double scroll the brief asked for.
//   Aizawa    (Aizawa–Uezu; the constants as circulated by Chaoscope) a .95 b .7 c .6 d 3.5 e .25 f .1.
//   Halvorsen (cyclically symmetric, a = 1.4) ẋ = −a x − 4y − 4z − y² (cyclic).

export const NAMES = ['thomas', 'cnn', 'aizawa', 'halvorsen'];
export const COUNT = NAMES.length;
export const STEPS = 8;        // RK2 steps per point — the cost driver in the vertex shader, kept ≤ 10
export const TRAVEL = 0.55;    // how far through the attractor's own extent those steps carry a point
// each attractor's natural half-extent, measured by the long RK4 run in tools/test_torus2.js
export const EXT = [4.5, 1.8, 1.85, 10.0];
export const THOMAS_B = 0.208;
export const CNN_A = [[1.24, -3.21, -3.21], [-3.21, 1.1, -4.4], [-3.21, 4.4, 1]];
export const AIZ = [0.95, 0.7, 0.6, 3.5, 0.25, 0.1];
export const HALV_A = 1.4;

const cnnF = (x) => 0.5 * (Math.abs(x + 1) - Math.abs(x - 1));

// The JS twins — the reference the node test compares the GLSL constants against, and the source of the step sizes.
export const FIELDS = [
  (x, y, z, o) => { o[0] = Math.sin(y) - THOMAS_B * x; o[1] = Math.sin(z) - THOMAS_B * y; o[2] = Math.sin(x) - THOMAS_B * z; return o; },
  (x, y, z, o) => {
    const f = [cnnF(x), cnnF(y), cnnF(z)], A = CNN_A;
    o[0] = -x + A[0][0] * f[0] + A[0][1] * f[1] + A[0][2] * f[2];
    o[1] = -y + A[1][0] * f[0] + A[1][1] * f[1] + A[1][2] * f[2];
    o[2] = -z + A[2][0] * f[0] + A[2][1] * f[1] + A[2][2] * f[2];
    return o;
  },
  (x, y, z, o) => {
    const [a, b, c, d, e, f] = AIZ;
    o[0] = (z - b) * x - d * y;
    o[1] = d * x + (z - b) * y;
    o[2] = c + a * z - z * z * z / 3 - (x * x + y * y) * (1 + e * z) + f * z * x * x * x;
    return o;
  },
  (x, y, z, o) => {
    o[0] = -HALV_A * x - 4 * y - 4 * z - y * y;
    o[1] = -HALV_A * y - 4 * z - 4 * x - z * z;
    o[2] = -HALV_A * z - 4 * x - 4 * y - x * x;
    return o;
  },
];

// Mean speed of each field on a fixed 7³ lattice inside its own extent — deterministic, computed once at load.
export function meanSpeed(i) {
  const F = FIELDS[i], e = EXT[i], o = [0, 0, 0];
  let s = 0, n = 0;
  for (let a = 0; a < 7; a++) {
    for (let b = 0; b < 7; b++) {
      for (let c = 0; c < 7; c++) {
        const x = (a / 3 - 1) * e * 0.8, y = (b / 3 - 1) * e * 0.8, z = (c / 3 - 1) * e * 0.8;
        F(x, y, z, o);
        s += Math.hypot(o[0], o[1], o[2]);
        n++;
      }
    }
  }
  return s / n;
}
// STEPS steps of size H[i] travel TRAVEL x the extent at the field's mean speed
export const H = FIELDS.map((_, i) => TRAVEL * EXT[i] / (STEPS * meanSpeed(i)));

// The JS twin of the shader's advect(): the same RK2 loop, the same normalisation, the same clamp.
export function advect(which, p, cen, rad, out = [0, 0, 0]) {
  const e = EXT[which], h = H[which], F = FIELDS[which], k1 = [0, 0, 0], k2 = [0, 0, 0];
  let ux = (p[0] - cen[0]) / rad * e, uy = (p[1] - cen[1]) / rad * e, uz = (p[2] - cen[2]) / rad * e;
  for (let i = 0; i < STEPS; i++) {
    F(ux, uy, uz, k1);
    F(ux + 0.5 * h * k1[0], uy + 0.5 * h * k1[1], uz + 0.5 * h * k1[2], k2);
    ux += h * k2[0]; uy += h * k2[1]; uz += h * k2[2];
  }
  let dx = ux / e * rad, dy = uy / e * rad, dz = uz / e * rad;
  const L = Math.hypot(dx, dy, dz), cap = rad * 1.6;
  if (L > cap) { const s = cap / L; dx *= s; dy *= s; dz *= s; }
  out[0] = cen[0] + dx; out[1] = cen[1] + dy; out[2] = cen[2] + dz;
  return out;
}

const n3 = (x) => x.toFixed(6);
// The GLSL twin. Every constant is written from the exported JS values, so the port cannot drift from the twin.
export const GLSL = `
#define ASTEPS ${STEPS}
uniform vec2 uMorphF;    // morph 0..1 · cross-fade between the two attractors 0..1
uniform vec3 uAttA;      // which, extent, step size
uniform vec3 uAttB;
float cnnF(float x) { return 0.5 * (abs(x + 1.0) - abs(x - 1.0)); }
vec3 atField(int w, vec3 u) {
  if (w == 0) return sin(u.yzx) - ${n3(THOMAS_B)} * u;                       // Thomas
  if (w == 1) {                                                             // 3-cell CNN
    vec3 f = vec3(cnnF(u.x), cnnF(u.y), cnnF(u.z));
    return -u + vec3(dot(vec3(${n3(CNN_A[0][0])}, ${n3(CNN_A[0][1])}, ${n3(CNN_A[0][2])}), f),
                     dot(vec3(${n3(CNN_A[1][0])}, ${n3(CNN_A[1][1])}, ${n3(CNN_A[1][2])}), f),
                     dot(vec3(${n3(CNN_A[2][0])}, ${n3(CNN_A[2][1])}, ${n3(CNN_A[2][2])}), f));
  }
  if (w == 2) {                                                             // Aizawa
    return vec3((u.z - ${n3(AIZ[1])}) * u.x - ${n3(AIZ[3])} * u.y,
                ${n3(AIZ[3])} * u.x + (u.z - ${n3(AIZ[1])}) * u.y,
                ${n3(AIZ[2])} + ${n3(AIZ[0])} * u.z - u.z * u.z * u.z / 3.0
                  - (u.x * u.x + u.y * u.y) * (1.0 + ${n3(AIZ[4])} * u.z) + ${n3(AIZ[5])} * u.z * u.x * u.x * u.x);
  }
  return -${n3(HALV_A)} * u - 4.0 * u.yzx - 4.0 * u.zxy - u.yzx * u.yzx;    // Halvorsen
}
// Normalise into the attractor's own coordinates, RK2 for ASTEPS steps, back, and clamp inside 1.6 x the nest radius.
vec3 atAdvect(vec3 att, vec3 p, vec3 cen, float rad) {
  int w = int(att.x);
  float e = att.y, h = att.z;
  vec3 u = (p - cen) / rad * e;
  for (int i = 0; i < ASTEPS; i++) {
    vec3 k1 = atField(w, u);
    u += h * atField(w, u + 0.5 * h * k1);
  }
  vec3 d = u / e * rad;
  float L = length(d);
  return cen + d * (L > rad * 1.6 ? rad * 1.6 / L : 1.0);
}
// The morph itself: at 0 the exact Hopf point, at 1 the advected one, cross-fading between two attractors on a change.
vec3 atMorph(vec3 p, vec3 cen, float rad) {
  if (uMorphF.x < 0.002) return p;
  vec3 q = atAdvect(uAttA, p, cen, rad);
  if (uMorphF.y > 0.001) q = mix(q, atAdvect(uAttB, p, cen, rad), uMorphF.y);
  return mix(p, q, uMorphF.x);
}
`;
